"""Every page renders its frame (sidebar, stepper, stage details) even before any export exists."""
import pytest
from app import create_app
from app.services.stages import STAGES

PAGES = [s["slug"] for s in STAGES]


@pytest.fixture
def client(tmp_path):
    return create_app({"DATA_DIR": str(tmp_path / "no-export-yet"), "TESTING": True}).test_client()


@pytest.mark.parametrize("slug", PAGES)
def test_page_renders_without_data(client, slug):
    r = client.get(f"/{slug}")
    assert r.status_code == 200
    html = r.get_data(as_text=True)
    assert "No export yet" in html and "Stage details" in html and f"pages/{slug}.js" in html


def test_root_is_the_overview(client):
    assert "01 · Overview" in client.get("/").get_data(as_text=True)


def test_unknown_page_is_404(client):
    assert client.get("/nope").status_code == 404


def test_no_ai_or_template_branding(client):
    html = client.get("/").get_data(as_text=True).lower()
    for word in ("telemetry core", "generated by", "powered by", "stitch"):
        assert word not in html
